CREATE TABLE IF NOT EXISTS study_series (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  rule JSON NOT NULL,
  UNIQUE (user_id,id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

ALTER TABLE study_sessions
  ADD COLUMN objective TEXT,
  ADD COLUMN series_id INT UNSIGNED,
  ADD COLUMN occurrence_date DATE,
  ADD COLUMN is_exception BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN planned_minutes INT UNSIGNED GENERATED ALWAYS AS (CEIL(TIMESTAMPDIFF(MICROSECOND,start_at,end_at)/60000000)) STORED,
  ADD COLUMN cancelled_at DATETIME(3),
  ADD COLUMN created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  ADD COLUMN updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  ADD UNIQUE (user_id,series_id,occurrence_date),
  ADD FOREIGN KEY (user_id,series_id) REFERENCES study_series(user_id,id) ON DELETE CASCADE;

ALTER TABLE availability_rules
  ADD COLUMN created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  ADD COLUMN updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3);
